/** El texto `id` en `idioma`, con sus marcadores reemplazados. Falla si falta: nunca un id a la vista. */
export function texto(idioma, id, valores = {}) {
  const t = TEXTOS[idioma] && TEXTOS[idioma][id];
  if (t === undefined) throw new Error(`falta el texto ${id} en ${idioma}`);
  return t.replace(/\{(\w+)\}/g, (_, k) => {
    if (!(k in valores)) throw new Error(`${id}: falta {${k}}`);
    return String(valores[k]);
  });
}
